"""OOB (Out-of-Band) command and acknowledgement protocol (Stage B6).

The target concept is a Sub-GHz (868/915 MHz) control channel.
In this prototype, the OOB link is SIMULATED IN SOFTWARE.
The same laptop Wi-Fi LAN carries the actual application messages.
This module emulates the OOB channel impairments in software:
  - Configurable message delay
  - Configurable message loss probability
  - Retry logic with timeout
  - Command deduplication
  - State transitions: PENDING → SENT → ACKED | FAILED | RETRYING

Label convention:
  "simulated OOB ACK"  = a software acknowledgement from the simulated RIS endpoint.
  NOT a response from physical RIS hardware or an actual Sub-GHz radio.
"""

import asyncio
import logging
import time
import uuid
import random
from dataclasses import dataclass, field
from enum import Enum
from typing import Optional, Dict, List, Callable


# ---------------------------------------------------------------------------
# Command schema
# ---------------------------------------------------------------------------

class CommandStatus(str, Enum):
    PENDING  = "PENDING"    # created, not yet sent
    SENT     = "SENT"       # transmitted over simulated OOB channel
    RETRYING = "RETRYING"   # retry in progress
    ACKED    = "ACKED"      # simulated RIS endpoint acknowledged
    FAILED   = "FAILED"     # exhausted retries or expired
    EXPIRED  = "EXPIRED"    # validity window passed before delivery


@dataclass
class OOBCommand:
    """Control command sent from Laptop B to a simulated RIS panel endpoint."""
    cmd_id: str
    target_panel_id: str        # e.g. "P01"
    zone_id: str
    codebook_index: int         # desired configuration
    config_version: int         # version being applied
    created_ts: float
    expires_ts: float           # validity window end
    reason: str                 # why this command was issued
    opt_id: Optional[str]       # optimizer result that triggered this command

    status: CommandStatus = CommandStatus.PENDING
    sent_ts: Optional[float] = None
    acked_ts: Optional[float] = None
    failed_ts: Optional[float] = None
    retry_count: int = 0
    ack_id: Optional[str] = None   # echo'd in ACK (simulated)
    last_error: Optional[str] = None

    def is_terminal(self) -> bool:
        return self.status in (CommandStatus.ACKED, CommandStatus.FAILED, CommandStatus.EXPIRED)

    def is_expired(self, now: float) -> bool:
        return now >= self.expires_ts

    def to_dict(self) -> dict:
        return {
            "cmd_id": self.cmd_id,
            "target_panel_id": self.target_panel_id,
            "zone_id": self.zone_id,
            "codebook_index": self.codebook_index,
            "config_version": self.config_version,
            "created_ts": self.created_ts,
            "expires_ts": self.expires_ts,
            "reason": self.reason,
            "opt_id": self.opt_id,
            "status": self.status.value,
            "sent_ts": self.sent_ts,
            "acked_ts": self.acked_ts,
            "failed_ts": self.failed_ts,
            "retry_count": self.retry_count,
            "ack_id": self.ack_id,
            "last_error": self.last_error,
        }


# ---------------------------------------------------------------------------
# OOB channel parameters
# ---------------------------------------------------------------------------

@dataclass
class OOBChannelParams:
    """Configurable simulated OOB channel impairments.

    These are SOFTWARE SIMULATION parameters, not real Sub-GHz radio specs.
    """
    delay_s: float = 0.05           # one-way simulated delay (seconds)
    loss_probability: float = 0.05  # probability a message is lost in transit
    retry_limit: int = 3            # max retransmission attempts per command
    timeout_s: float = 2.0          # per-attempt timeout
    validity_window_s: float = 10.0 # command expiry from creation time
    max_pending_per_panel: int = 1  # duplicate-command protection per panel


# ---------------------------------------------------------------------------
# OOB Controller
# ---------------------------------------------------------------------------

class OOBController:
    """Manages OOB command lifecycle: issue, transmit, retry, ack/fail.

    The "transmission" is a simulated asyncio task that sleeps for delay_s
    and randomly drops messages according to loss_probability.
    ACKs are generated by the SimulatedRISEndpoint within this module.
    """

    def __init__(self,
                 params: Optional[OOBChannelParams] = None,
                 seed: int = 42,
                 logger: Optional[logging.Logger] = None,
                 on_acked: Optional[Callable[[OOBCommand], None]] = None,
                 on_failed: Optional[Callable[[OOBCommand], None]] = None):
        self.params = params or OOBChannelParams()
        self._rng = random.Random(seed)
        self.log = logger or logging.getLogger("laptop_b.oob")
        self.on_acked = on_acked
        self.on_failed = on_failed

        # Active commands indexed by cmd_id
        self._commands: Dict[str, OOBCommand] = {}
        # Per-panel: set of active (non-terminal) cmd_ids
        self._panel_active: Dict[str, set] = {}

        # Stats counters
        self.stats = {
            "tx_attempts": 0,
            "tx_lost": 0,
            "acks_received": 0,
            "nacks_received": 0,
            "retries": 0,
            "timeouts": 0,
            "commands_issued": 0,
            "commands_acked": 0,
            "commands_failed": 0,
            "duplicates_rejected": 0,
        }
        self.history: List[OOBCommand] = []
        self.max_history = 500

    def issue_command(self, panel_id: str, zone_id: str, codebook_index: int,
                      config_version: int, reason: str,
                      opt_id: Optional[str] = None,
                      clock: Callable[[], float] = time.time) -> Optional[OOBCommand]:
        """Create and enqueue a new OOB command.

        Returns None if the panel already has an active command (duplicate protection).
        """
        now = clock()
        p = self.params
        active = self._panel_active.get(panel_id, set())
        active_count = sum(1 for cid in active
                           if not self._commands[cid].is_terminal())
        if active_count >= p.max_pending_per_panel:
            self.stats["duplicates_rejected"] += 1
            self.log.warning(
                "Panel %s already has %d active command(s); rejecting new cmd (duplicate protection)",
                panel_id, active_count,
            )
            return None

        cmd = OOBCommand(
            cmd_id=uuid.uuid4().hex[:16],
            target_panel_id=panel_id,
            zone_id=zone_id,
            codebook_index=codebook_index,
            config_version=config_version,
            created_ts=now,
            expires_ts=now + p.validity_window_s,
            reason=reason,
            opt_id=opt_id,
        )
        self._commands[cmd.cmd_id] = cmd
        self._panel_active.setdefault(panel_id, set()).add(cmd.cmd_id)
        self.stats["commands_issued"] += 1
        self.log.info("OOB command issued: cmd_id=%s panel=%s codebook=%d reason=%s",
                      cmd.cmd_id, panel_id, codebook_index, reason)
        return cmd

    async def transmit_and_await_ack(self, cmd: OOBCommand,
                                      clock: Callable[[], float] = time.time) -> bool:
        """Drive one command through the simulated OOB channel until ACKED or FAILED.

        Returns True if ACKED, False if FAILED/EXPIRED.
        This is a SIMULATED OOB exchange; no real Sub-GHz radio is involved.
        """
        p = self.params
        for attempt in range(p.retry_limit + 1):
            now = clock()
            if cmd.is_expired(now):
                cmd.status = CommandStatus.EXPIRED
                cmd.last_error = "command expired before delivery"
                self.log.warning("OOB cmd %s EXPIRED (attempt %d)", cmd.cmd_id, attempt)
                self._finalize(cmd, clock)
                return False

            cmd.status = CommandStatus.SENT if attempt == 0 else CommandStatus.RETRYING
            cmd.sent_ts = now
            if attempt > 0:
                cmd.retry_count += 1
                self.stats["retries"] += 1
                self.log.info("OOB retry %d cmd_id=%s panel=%s",
                              attempt, cmd.cmd_id, cmd.target_panel_id)

            self.stats["tx_attempts"] += 1
            # Simulate OOB channel delay
            await asyncio.sleep(p.delay_s)

            # Simulate OOB channel loss
            if self._rng.random() < p.loss_probability:
                self.stats["tx_lost"] += 1
                self.log.debug("OOB TX lost (simulated loss): cmd_id=%s attempt=%d",
                               cmd.cmd_id, attempt)
                # Simulate ACK timeout
                try:
                    await asyncio.wait_for(asyncio.sleep(p.timeout_s), timeout=p.timeout_s)
                except asyncio.TimeoutError:
                    pass
                self.stats["timeouts"] += 1
                continue

            # Simulate ACK from the simulated RIS endpoint (software model)
            await asyncio.sleep(p.delay_s)  # return trip delay
            ack_id = uuid.uuid4().hex[:12]
            cmd.ack_id = ack_id
            cmd.acked_ts = clock()
            cmd.status = CommandStatus.ACKED
            self.stats["acks_received"] += 1
            self.stats["commands_acked"] += 1
            self.log.info(
                "Simulated OOB ACK received: cmd_id=%s ack_id=%s panel=%s codebook=%d",
                cmd.cmd_id, ack_id, cmd.target_panel_id, cmd.codebook_index,
            )
            self._finalize(cmd, clock)
            if self.on_acked:
                self.on_acked(cmd)
            return True

        # Exhausted retries
        cmd.status = CommandStatus.FAILED
        cmd.last_error = f"exhausted {p.retry_limit} retries"
        cmd.failed_ts = clock()
        self.stats["commands_failed"] += 1
        self.log.error("OOB cmd FAILED: cmd_id=%s panel=%s after %d retries",
                       cmd.cmd_id, cmd.target_panel_id, cmd.retry_count)
        self._finalize(cmd, clock)
        if self.on_failed:
            self.on_failed(cmd)
        return False

    def _finalize(self, cmd: OOBCommand, clock):
        self._panel_active.get(cmd.target_panel_id, set()).discard(cmd.cmd_id)
        self.history.append(cmd)
        if len(self.history) > self.max_history:
            self.history.pop(0)

    def active_commands(self) -> List[OOBCommand]:
        return [c for c in self._commands.values() if not c.is_terminal()]

    def all_commands(self) -> List[OOBCommand]:
        return list(self._commands.values())

    def stats_summary(self) -> str:
        s = self.stats
        return (
            f"OOB TX_attempts={s['tx_attempts']} lost={s['tx_lost']} "
            f"ACK={s['acks_received']} retries={s['retries']} timeouts={s['timeouts']} "
            f"commands: issued={s['commands_issued']} acked={s['commands_acked']} "
            f"failed={s['commands_failed']} dup_rejected={s['duplicates_rejected']}"
        )
